"""game/clock —— 快进编排(玩家对时间说的话)。

**"快进 = 跳到, 不是快放"**(设计决定 #13): 引擎确定性 + 可无头跑, 所以
快进就是【同一帧里多推进几个 tick】, 不是把 tick 放快。好处:
  · 快进区间不需要渲染, 也不该触发 LLM(D7: 快进区间降级到规则驱动)
  · 快进有代价 —— 你的需求也在掉, 而【世界在变你没看见】(决定 #14)

档位是【游戏概念】, 不是内核概念: 内核只认识 tick。这里是从人话到 tick
的唯一翻译点。tick 与墙钟的换算(PUSH_HZ / 时间预算)在 `server.py`, 那是
传输的事, 不是编排的事。
"""
from __future__ import annotations

# 档位 → 真实 ticks/秒。1x = 1 tick/秒 → 一天 1440 tick = 24 分钟(和现实同速)。
# pause 是 0 而不是"很小的数": 暂停必须真的不推进(否则世界在背后偷偷走)。
SPEED_TPS: dict[str, int] = {
    "pause": 0, "1x": 1, "10x": 10, "100x": 100, "1000x": 1000,
}


def real_tps(speed: str) -> int:
    """当前档位真实 ticks/秒(1x = 1 tick/秒, 供前端做本地 tick 外推)。

    前端拿着它自己外推时钟, 所以不要在这里做「实际比标称慢一半」的修正 ——
    那会让前端越跑越超前(见 server.loop 里用真实 dt 累加的那段注释)。
    """
    return SPEED_TPS[speed]
